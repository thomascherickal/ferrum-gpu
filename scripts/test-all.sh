#!/usr/bin/env bash
# Run every test in every crate and measure coverage, in one go. Prints a test report and a
# coverage report to the console and writes them to LAST-TEST-RESULTS.md and LAST-COVERAGE-RESULTS.md.
#
#   scripts/test-all.sh          # two full runs (real GPU, then no GPU), merged coverage
#   FLOOR=99 scripts/test-all.sh # also exit non-zero if total line coverage is below FLOOR
#
# Needs cargo-llvm-cov + llvm-tools and python3. Run it alone (one cargo job at a time, CLAUDE.md rule 7).
# Exit code: 0 all tests pass (and floor met), 1 a test failed, 2 coverage below FLOOR.
set -uo pipefail
cd "$(dirname "$0")/.."
export CARGO_BUILD_JOBS="${CARGO_BUILD_JOBS:-3}"
out="${TMPDIR:-/tmp}/ferrum-test-all.$$"; mkdir -p "$out"
trap 'rm -rf "$out"' EXIT

cargo llvm-cov clean --workspace >/dev/null 2>&1
# The GPU run uses the default adapter; the second run hides every adapter, so the "skip when there
# is no GPU" branches execute. --no-fail-fast: one failing test does not hide the rest.
echo "== run 1/2: with the GPU =="
cargo llvm-cov --workspace --no-report --no-fail-fast -- --test-threads 1 2>&1 | grep -v libEGL | tee "$out/gpu.log" | grep -E "^(test result|error|warning: unused)|FAILED|panicked" 
echo "== run 2/2: no GPU =="
FERRUM_GPU_ADAPTER=no-such-adapter cargo llvm-cov --workspace --no-report --no-fail-fast -- --test-threads 1 2>&1 | grep -v libEGL | tee "$out/nogpu.log" | grep -E "^(test result|error)|FAILED|panicked"
cargo llvm-cov report --json --summary-only --output-path "$out/cov.json" >/dev/null 2>&1
cargo llvm-cov report --summary-only >"$out/cov.txt" 2>&1

OUT="$out" FLOOR="${FLOOR:-}" python3 - <<'PY'
import json, os, re, sys, subprocess, datetime
out = os.environ["OUT"]; floor = os.environ["FLOOR"]
now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
git = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
dirty = " (uncommitted changes)" if subprocess.run(["git", "status", "--porcelain"], capture_output=True, text=True).stdout.strip() else ""

def parse(path):
    """Per test binary: (name, passed, failed, ignored); plus the names of failed tests."""
    rows, failed, cur = [], [], None
    for l in open(path, errors="replace"):
        m = re.search(r"Running .*deps/([A-Za-z0-9_]+?)-[0-9a-f]{8,}", l) or re.search(r"Running (\S+)", l)
        if m: cur = m.group(1); continue
        m = re.search(r"Doc-tests (\S+)", l)
        if m: cur = "doc:" + m.group(1); continue
        m = re.match(r"test result: \w+\. (\d+) passed; (\d+) failed; (\d+) ignored", l)
        if m and cur: rows.append((cur, *map(int, m.groups())))
        m = re.match(r"test (\S+) \.\.\. FAILED", l)
        if m: failed.append(m.group(1))
    return rows, failed

tot_fail = 0
md = [f"# Last test results\n", f"Generated by `scripts/test-all.sh` on {now}, commit {git}{dirty}. Overwritten on every run.\n"]
for label, f in (("With the GPU", "gpu.log"), ("No GPU (every adapter hidden)", "nogpu.log")):
    rows, failed = parse(os.path.join(out, f))
    p = sum(r[1] for r in rows); fl = sum(r[2] for r in rows); ig = sum(r[3] for r in rows); tot_fail += fl
    md += [f"## {label}: {p} passed, {fl} failed, {ig} ignored\n", "| test binary | passed | failed | ignored |", "|---|---:|---:|---:|"]
    agg = {}
    for n, a, b, c in rows:
        x = agg.setdefault(n, [0, 0, 0]); x[0] += a; x[1] += b; x[2] += c
    md += [f"| {n} | {a} | {b} | {c} |" for n, (a, b, c) in sorted(agg.items()) if a or b or c]
    if failed: md += ["", "Failed tests:", *[f"- `{t}`" for t in sorted(set(failed))]]
    md.append("")
    print(f"tests, {label}: {p} passed, {fl} failed, {ig} ignored")
open("LAST-TEST-RESULTS.md", "w").write("\n".join(md))

j = json.load(open(os.path.join(out, "cov.json")))["data"][0]
t = j["totals"]; root = os.getcwd() + "/"
cov = [f"# Last coverage results\n", f"Generated by `scripts/test-all.sh` on {now}, commit {git}{dirty}. Merged line coverage of both test runs (GPU and no GPU). Overwritten on every run. JavaScript in `ferrum_gpu_gui/web/` and the `benches/` programs are not instrumented.\n",
       f"**Total: {t['lines']['percent']:.2f}% of lines ({t['lines']['count']-t['lines']['covered']} of {t['lines']['count']} missed), {t['regions']['percent']:.2f}% of regions, {t['functions']['percent']:.2f}% of functions.**\n",
       "| file | lines | missed | regions | functions |", "|---|---:|---:|---:|---:|"]
for f in sorted(j["files"], key=lambda f: f["filename"]):
    s = f["summary"]; n = f["filename"].replace(root, "")
    cov.append(f"| {n} | {s['lines']['percent']:.2f}% | {s['lines']['count']-s['lines']['covered']} | {s['regions']['percent']:.2f}% | {s['functions']['percent']:.2f}% |")
open("LAST-COVERAGE-RESULTS.md", "w").write("\n".join(cov) + "\n")
print(f"coverage: {t['lines']['percent']:.2f}% lines, {t['regions']['percent']:.2f}% regions, {t['functions']['percent']:.2f}% functions")
code = 1 if tot_fail else 0
if floor and t["lines"]["percent"] < float(floor):
    print(f"coverage {t['lines']['percent']:.2f}% is below the floor {floor}%"); code = code or 2
sys.exit(code)
PY
rc=$?
echo; echo "---- coverage by file (lowest 8) ----"
sort -t'|' -k3 -n LAST-COVERAGE-RESULTS.md 2>/dev/null | grep '^| ' | grep -v '^| file\|^|---' | awk -F'|' '{print $2 $3}' | sort -k2 -n | head -8
echo "reports: LAST-TEST-RESULTS.md  LAST-COVERAGE-RESULTS.md"
exit $rc
