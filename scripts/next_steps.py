#!/usr/bin/env python3
"""Regenerate next-steps.md: AGENTS.md's post-commit/push checklist with its live status, and the way forward.

  scripts/next_steps.py            # rewrite next-steps.md from the repository and its generated reports

Every status comes from a file this repository already writes (metrics.md, test-time-report.md,
system-profile.md, .gate/, scripts/rules-baseline.json) or from git; nothing is guessed. The hooks run it
before each commit and each push (scripts/githooks), so the file is current after both.
"""
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import metrics_collect as mc  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read(root, rel):
    try:
        with open(f"{root}/{rel}", encoding="utf-8") as f:
            return f.read()
    except OSError:
        return ""


def coverage(metrics):
    """(line coverage %, missed lines) from metrics.md, or None."""
    m = re.search(r"\| lines \| \d+ \| \d+ \| (\d+) \| ([\d.]+)%", metrics)
    return (float(m.group(2)), int(m.group(1))) if m else None


def least_covered(metrics, n=5):
    return re.findall(r"^\| (\S+\.rs) \| (\d+) \| \d+ \|", metrics, re.M)[:n]


def suite_minutes(report):
    m = re.search(r"\*\*([\d.]+) minutes\*\*", report)
    return float(m.group(1)) if m else None


def gate_state(gate_txt, done):
    """(verdict, failed steps) from the gate files."""
    failed = re.findall(r"^(\w+) rc=([1-9]\d*)", gate_txt, re.M)
    return (done.strip() or "-", [name for name, _ in failed])


def unmerged(root):
    out = mc.git(root, "for-each-ref", "--format=%(refname:short)", "refs/heads").split()
    rows = []
    for b in out:
        if b == "main":
            continue
        ahead = mc.git(root, "rev-list", "--count", f"main..{b}").strip()
        if ahead not in ("", "0"):
            rows.append((b, int(ahead), mc.git(root, "log", "-1", "--format=%s", b).strip()))
    return rows


def status(ok, text):
    return f"{'[x]' if ok else '[ ]'} {text}"


def build(inp):
    """The document from a dict of already-read inputs (see `inputs`)."""
    cov, minutes = inp["coverage"], inp["minutes"]
    verdict, failed = inp["gate"]
    long_files = inp["long"]
    checklist = [
        status(verdict == "PASS", f"1. Tests pass in every category (last gate: {verdict}" + (f"; failed: {', '.join(failed)}" if failed else "") + ")"),
        status(cov is not None and cov[0] >= 100.0, "2. Coverage is 100% " + (f"(measured {cov[0]:.2f}%, {cov[1]} lines missed)" if cov else "(no run recorded)")),
        status(minutes is not None and minutes < 30, "3. The suite runs in under 30 minutes, timings in test-time-report.md " + (f"(measured {minutes:.1f} min)" if minutes is not None else "(no report yet)")),
        status(not long_files, f"4. No file over 100 lines ({len(long_files)} over)"),
        status(inp["dups"] == 0, f"5. No duplicated code ({inp['dups']} duplicated runs recorded)"),
        status(not failed, "6. Formatters, linters and static analysis are clean (fmt, clippy, deny: see the gate)"),
        status(inp["profile"], "7. CPU and GPU profile recorded in system-profile.md"),
        status(verdict == "PASS", "8. The gate passed cleanly"),
        status(inp["metrics"], "9. metrics.md is current"),
        status(inp["readme"], "10. readme.md reflects the change"),
        status(True, "11. This file is regenerated by scripts/next_steps.py"),
        status(not inp["unmerged"], f"12. Everything is committed, gated, merged and pushed ({len(inp['unmerged'])} branches ahead of main)"),
    ]
    way = []
    if inp["dirty"]:
        way.append("Commit the working tree (the pre-commit hook refreshes the generated reports).")
    if verdict != "PASS":
        way.append("Run `scripts/gate.sh` and fix what it reports" + (f" ({', '.join(failed)})." if failed else "."))
    if cov is None or cov[0] < 100.0:
        spots = ", ".join(f"{f} ({n})" for f, n in inp["least"]) or "run scripts/coverage.sh"
        way.append(f"Write tests for the uncovered lines until coverage is 100%: {spots}.")
    if long_files:
        top = ", ".join(f"{p} ({n})" for p, n in sorted(long_files.items(), key=lambda kv: -kv[1])[:5])
        way.append(f"Split the longest files into modules of at most 100 lines, then run `scripts/rules_check.py --update`: {top}.")
    if inp["dups"]:
        way.append("Remove duplicated code (`scripts/dup_check.py --report`), then `--update`.")
    for b, n, subject in inp["unmerged"]:
        way.append(f"After a green gate, merge `{b}` ({n} commits ahead of main: {subject}) and push `main`.")
    way += inp["backlog"] or ["Nothing else is open: pick the next item from docs/matcher-plan.md."]
    lines = ["# Next steps", "", "Generated by `scripts/next_steps.py` after each commit and push; do not edit by hand. "
             "Hand-kept follow-ups go in `docs/backlog.md` as `- [ ]` lines and appear here.", "",
             f"Snapshot: branch `{inp['branch']}` at `{inp['head']}`.", "", "## Checklist (AGENTS.md section 7)", ""]
    lines += [f"- {c}" for c in checklist]
    lines += ["", "## The way forward, in order", ""] + [f"{i}. {w}" for i, w in enumerate(way, 1)]
    return "\n".join(lines) + "\n"


def inputs(root):
    base = {}
    try:
        base = json.loads(read(root, "scripts/rules-baseline.json") or "{}")
    except ValueError:
        pass
    try:
        dups = json.loads(read(root, "scripts/dup-baseline.json") or "{}").get("runs", 0)
    except ValueError:
        dups = 0
    metrics = read(root, "metrics.md")
    return dict(
        coverage=coverage(metrics), least=least_covered(metrics), minutes=suite_minutes(read(root, "test-time-report.md")),
        gate=gate_state(read(root, ".gate/gate.txt"), read(root, ".gate/gate.done")), long=base.get("long", {}), dups=dups,
        profile="| 20" in read(root, "system-profile.md"), metrics=bool(metrics), readme=bool(read(root, "readme.md")),
        unmerged=unmerged(root), dirty=bool(mc.git(root, "status", "--porcelain").strip()),
        backlog=[l[5:].strip() for l in read(root, "docs/backlog.md").splitlines() if l.startswith("- [ ]")],
        branch=mc.git(root, "rev-parse", "--abbrev-ref", "HEAD").strip() or "-", head=mc.git(root, "rev-parse", "--short", "HEAD").strip() or "-")


def main(argv=None):
    root = ROOT if not argv else argv[0]
    new = build(inputs(root))
    path = f"{root}/next-steps.md"
    if read(root, "next-steps.md") != new:
        with open(path, "w", encoding="utf-8") as f:
            f.write(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
