#!/usr/bin/env python3
"""Run every test in every crate and measure coverage, in one go. Prints a test report and a coverage report to
the console and writes them to last-test-results.md and last-coverage-results.md.

  scripts/all_tests.py          # two full runs (real GPU, then no GPU), merged coverage (scripts/test-all.sh calls this)
  FLOOR=99 scripts/all_tests.py # also exit non-zero if total line coverage is below FLOOR

Needs cargo-llvm-cov + llvm-tools and Python. Run it alone (one cargo job at a time, CLAUDE.md rule 7).
Exit code: 0 all tests pass (and floor met), 1 a test failed, 2 coverage below FLOOR. The temporary
directory with the raw logs is left in place when the run ends (no rm: the command ban list).
"""
import datetime
import json
import os
import re
import sys
import tempfile

os.environ["PYTHONDONTWRITEBYTECODE"] = "1"  # tracked __pycache__ must stay as committed
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import all_tests_reports as reports  # noqa: E402
import runner  # noqa: E402

CARGO = ["cargo", "llvm-cov", "--workspace", "--no-report", "--no-fail-fast", "--", "--test-threads", "1"]
NOT_EGL = "libEGL"


def one_run(title, env, log, interesting):
    """Run the tests once: raw output (minus libEGL noise) to `log`, the lines that matter to the console."""
    print(title)
    wanted = re.compile(interesting)
    runner.run_tee(CARGO, log, env, lambda l: NOT_EGL not in l and wanted.search(l) is not None)


def main(argv=None):
    if runner.help_requested(sys.argv[1:] if argv is None else argv, __doc__):
        return 0
    os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    os.environ.setdefault("CARGO_BUILD_JOBS", "3")
    floor = os.environ.get("FLOOR", "")
    out = os.path.join(os.environ.get("TMPDIR") or tempfile.gettempdir(), f"ferrum-test-all.{os.getpid()}")
    os.makedirs(out, exist_ok=True)
    runner.run_quiet(["cargo", "llvm-cov", "clean", "--workspace"])
    # The second run hides every adapter, so the "skip when there is no GPU" branches execute. --no-fail-fast:
    # one failing test does not hide the rest.
    one_run("== run 1/2: with the GPU ==", None, f"{out}/gpu.log", r"^(test result|error|warning: unused)|FAILED|panicked")
    one_run("== run 2/2: no GPU ==", {"FERRUM_GPU_ADAPTER": "no-such-adapter"}, f"{out}/nogpu.log",
            r"^(test result|error)|FAILED|panicked")
    runner.run_quiet(["cargo", "llvm-cov", "report", "--json", "--summary-only", "--output-path", f"{out}/cov.json"])
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    head = runner.captured(["git", "rev-parse", "--short", "HEAD"]).strip()
    dirty = " (uncommitted changes)" if runner.captured(["git", "status", "--porcelain"]).strip() else ""
    md, total_failed = [f"# Last test results\n", f"Generated by `scripts/test-all.sh` on {now}, commit {head}{dirty}. "
                        "Overwritten on every run.\n"], 0
    for label, name in (("With the GPU", "gpu.log"), ("No GPU (every adapter hidden)", "nogpu.log")):
        with open(f"{out}/{name}", encoding="utf-8", errors="replace") as f:
            section, passed, failed, ignored = reports.test_section(label, *reports.parse(f))
        md, total_failed = md + section, total_failed + failed
        print(f"tests, {label}: {passed} passed, {failed} failed, {ignored} ignored")
    with open("last-test-results.md", "w", encoding="utf-8") as f:
        f.write("\n".join(md))
    with open(f"{out}/cov.json", encoding="utf-8") as f:
        text, t = reports.coverage_report(json.load(f)["data"][0], os.getcwd() + os.sep, now, head + dirty)
    with open("last-coverage-results.md", "w", encoding="utf-8") as f:
        f.write(text)
    print(f"coverage: {t['lines']['percent']:.2f}% lines, {t['regions']['percent']:.2f}% regions, "
          f"{t['functions']['percent']:.2f}% functions")
    code = 1 if total_failed else 0
    if floor and t["lines"]["percent"] < float(floor):
        print(f"coverage {t['lines']['percent']:.2f}% is below the floor {floor}%")
        code = code or 2
    print("\n---- coverage by file (lowest 8) ----\n" + "\n".join(reports.lowest(text)))
    print("reports: last-test-results.md  last-coverage-results.md")
    return code


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
