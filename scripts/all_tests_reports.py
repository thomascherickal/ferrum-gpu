"""The two Markdown reports of all_tests.py (last-test-results.md, last-coverage-results.md) and the figures
they are built from. Pure functions: text and numbers in, text out."""
import re


def parse(lines):
    """Per test binary (name, passed, failed, ignored) from `cargo test` output, plus the failed test names."""
    rows, failed, cur = [], [], None
    for l in lines:
        m = re.search(r"Running .*deps/([A-Za-z0-9_]+?)-[0-9a-f]{8,}", l) or re.search(r"Running (\S+)", l)
        if m:
            cur = m.group(1)
            continue
        m = re.search(r"Doc-tests (\S+)", l)
        if m:
            cur = "doc:" + m.group(1)
            continue
        m = re.match(r"test result: \w+\. (\d+) passed; (\d+) failed; (\d+) ignored", l)
        if m and cur:
            rows.append((cur, *map(int, m.groups())))
        m = re.match(r"test (\S+) \.\.\. FAILED", l)
        if m:
            failed.append(m.group(1))
    return rows, failed


def test_section(label, rows, failed):
    """(Markdown lines, passed, failed, ignored) of one run."""
    p, fl, ig = (sum(r[i] for r in rows) for i in (1, 2, 3))
    md = [f"## {label}: {p} passed, {fl} failed, {ig} ignored\n", "| test binary | passed | failed | ignored |",
          "|---|---:|---:|---:|"]
    agg = {}
    for n, a, b, c in rows:
        x = agg.setdefault(n, [0, 0, 0])
        x[0], x[1], x[2] = x[0] + a, x[1] + b, x[2] + c
    md += [f"| {n} | {a} | {b} | {c} |" for n, (a, b, c) in sorted(agg.items()) if a or b or c]
    if failed:
        md += ["", "Failed tests:", *[f"- `{t}`" for t in sorted(set(failed))]]
    return md + [""], p, fl, ig


def coverage_report(data, root, now, git):
    """(Markdown, totals) from the `totals` and `files` of a `cargo llvm-cov report --json` export."""
    t = data["totals"]
    miss = t["lines"]["count"] - t["lines"]["covered"]
    md = ["# Last coverage results\n", f"Generated by `scripts/test-all.sh` on {now}, commit {git}. Merged line "
          "coverage of both test runs (GPU and no GPU). Overwritten on every run. JavaScript in "
          "`ferrum_gpu_gui/web/` and the `benches/` programs are not instrumented.\n",
          f"**Total: {t['lines']['percent']:.2f}% of lines ({miss} of {t['lines']['count']} missed), "
          f"{t['regions']['percent']:.2f}% of regions, {t['functions']['percent']:.2f}% of functions.**\n",
          "| file | lines | missed | regions | functions |", "|---|---:|---:|---:|---:|"]
    for f in sorted(data["files"], key=lambda f: f["filename"]):
        s = f["summary"]
        md.append(f"| {f['filename'].replace(root, '')} | {s['lines']['percent']:.2f}% | "
                  f"{s['lines']['count'] - s['lines']['covered']} | {s['regions']['percent']:.2f}% | "
                  f"{s['functions']['percent']:.2f}% |")
    return "\n".join(md) + "\n", t


def lowest(markdown, n=8):
    """The `n` files with the lowest line coverage in the coverage report, as "name  percent" strings."""
    rows = [l.split("|")[1:3] for l in markdown.splitlines() if l.startswith("| ") and not l.startswith(("| file", "|---"))]
    rows.sort(key=lambda r: float(r[1].strip().rstrip("%")))
    return [f"{a}{b}" for a, b in rows[:n]]
