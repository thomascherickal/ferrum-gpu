#!/usr/bin/env python3
"""Render test-time-report.md from the per-test times scripts/test-time-limit.sh saves.

  TIMES_OUT=target/test-times.txt scripts/test-time-limit.sh 0     # every test in its own process
  python3 scripts/timing_report.py target/test-times.txt             # writes test-time-report.md

Each input line is "<seconds> <test binary> <test name>". AGENTS.md: the whole suite must run in under
30 minutes, and slow tests are flagged. The times here are per-process sums, so they include process
start-up; the wall-clock of the whole gate is in metrics.md.
"""
import collections
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from generated_diagrams import pie  # noqa: E402
import datetime
import os
import re
import subprocess
import sys

SLOW_SECONDS = 5.0
LIMIT_MINUTES = 30


def parse(text):
    """[(seconds, suite, name)] from the times file; malformed lines are skipped."""
    rows = []
    for line in text.splitlines():
        parts = line.split(None, 2)
        if len(parts) == 3:
            try:
                rows.append((float(parts[0]), re.sub(r"-[0-9a-f]{16}$", "", parts[1]), parts[2]))
            except ValueError:
                continue
    return rows


def render(rows, commit, when):
    total = sum(r[0] for r in rows)
    by_suite = collections.defaultdict(lambda: [0, 0.0])
    for sec, suite, _ in rows:
        by_suite[suite][0] += 1
        by_suite[suite][1] += sec
    slow = sorted((r for r in rows if r[0] >= SLOW_SECONDS), reverse=True)
    out = [
        "# Test time report",
        "",
        "Generated by `scripts/timing_report.py` from `scripts/test-time-limit.sh` (every test in its own process); "
        "do not edit by hand.",
        "",
        pie("Test time by binary (seconds)", [(k, round(v[1], 1)) for k, v in sorted(by_suite.items(), key=lambda kv: -kv[1][1])[:8]]),
        "",
        f"Measured {when} on commit `{commit}`: **{len(rows)}** tests, **{total / 60:.1f} minutes** in total "
        f"(limit {LIMIT_MINUTES} minutes: {'within' if total / 60 < LIMIT_MINUTES else 'OVER'} the limit).",
        "",
        "## By test binary",
        "",
        "| binary | tests | seconds |",
        "|---|---|---|",
    ]
    out += [f"| {s} | {n} | {t:.1f} |" for s, (n, t) in sorted(by_suite.items(), key=lambda kv: -kv[1][1])]
    out += ["", f"## Slow tests (at least {SLOW_SECONDS:.0f} s each: optimise these first)", ""]
    out += ["| seconds | test |", "|---|---|"] + [f"| {s:.1f} | {suite}: {n} |" for s, suite, n in slow[:20]] if slow else ["None."]
    out += ["", "## Ten slowest", "", "| seconds | test |", "|---|---|"]
    out += [f"| {s:.2f} | {suite}: {n} |" for s, suite, n in sorted(rows, reverse=True)[:10]]
    return "\n".join(out) + "\n"


def main(argv=None):
    args = sys.argv[1:] if argv is None else argv
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    rows = parse(open(args[0], encoding="utf-8").read())
    if not rows:
        print("no test times found", file=sys.stderr)
        return 1
    commit = subprocess.run(["git", "-C", root, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip() or "-"
    when = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    with open(f"{root}/test-time-report.md", "w", encoding="utf-8") as f:
        f.write(render(rows, commit, when))
    return 0


if __name__ == "__main__":
    sys.exit(main())
