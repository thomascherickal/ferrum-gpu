//! Activations and scratch buffers for one (batch, tokens) shape.

use crate::device::{Gpu, GpuError};
use crate::tensor::GpuBuf;
use ferrum_ref::gpt2::Config;

/// Activations and scratch for one `(batch, t)` shape.
pub(super) struct Acts {
    pub(super) batch: usize,
    pub(super) t: usize,
    pub(super) x: Vec<GpuBuf>,
    pub(super) h1: Vec<GpuBuf>,
    pub(super) q: Vec<GpuBuf>,
    pub(super) k: Vec<GpuBuf>,
    pub(super) v: Vec<GpuBuf>,
    pub(super) probs: Vec<GpuBuf>,
    pub(super) a: Vec<GpuBuf>,
    pub(super) x2: Vec<GpuBuf>,
    pub(super) h2: Vec<GpuBuf>,
    pub(super) f1: Vec<GpuBuf>,
    pub(super) act: Vec<GpuBuf>,
    pub(super) o: GpuBuf,
    pub(super) f2: GpuBuf,
    pub(super) tmp_c: GpuBuf,
    pub(super) tmp_h: GpuBuf,
    pub(super) hf: GpuBuf,
    pub(super) logits: GpuBuf,
    pub(super) dlogits: GpuBuf,
    pub(super) row_loss: GpuBuf,
    pub(super) loss: GpuBuf,
    pub(super) dhf: GpuBuf,
    pub(super) dx_a: GpuBuf,
    pub(super) dx_b: GpuBuf,
    pub(super) dact: GpuBuf,
    pub(super) df1: GpuBuf,
    pub(super) dh2: GpuBuf,
    pub(super) dx2ln: GpuBuf,
    pub(super) dx2: GpuBuf,
    pub(super) da: GpuBuf,
    pub(super) dq: GpuBuf,
    pub(super) dk: GpuBuf,
    pub(super) dv: GpuBuf,
    pub(super) dh1a: GpuBuf,
    pub(super) dh1b: GpuBuf,
    pub(super) dh1c: GpuBuf,
    pub(super) t1: GpuBuf,
    pub(super) dh1: GpuBuf,
    pub(super) dxln: GpuBuf,
    pub(super) stats: GpuBuf,
    pub(super) dot: GpuBuf,
    pub(super) ds: GpuBuf,
    pub(super) junk_v: GpuBuf,
}

impl Acts {
    pub(super) fn new(gpu: &Gpu, c: &Config, batch: usize, t: usize) -> Result<Acts, GpuError> {
        let (r, d, h, v) = (batch * t, c.dim, c.hidden, c.vocab);
        let z = |n: usize| gpu.zeros(n);
        let per = |n: usize| (0..c.layers).map(|_| z(n)).collect::<Result<Vec<_>, _>>();
        Ok(Acts {
            batch,
            t,
            x: (0..=c.layers).map(|_| z(r * d)).collect::<Result<_, _>>()?,
            h1: per(r * d)?,
            q: per(r * d)?,
            k: per(r * d)?,
            v: per(r * d)?,
            probs: per(batch * c.heads * t * t)?,
            a: per(r * d)?,
            x2: per(r * d)?,
            h2: per(r * d)?,
            f1: per(r * h)?,
            act: per(r * h)?,
            o: z(r * d)?,
            f2: z(r * d)?,
            tmp_c: z(r * d)?,
            tmp_h: z(r * h)?,
            hf: z(r * d)?,
            logits: z(r * v)?,
            dlogits: z(r * v)?,
            row_loss: z(r)?,
            loss: z(1)?,
            dhf: z(r * d)?,
            dx_a: z(r * d)?,
            dx_b: z(r * d)?,
            dact: z(r * h)?,
            df1: z(r * h)?,
            dh2: z(r * d)?,
            dx2ln: z(r * d)?,
            dx2: z(r * d)?,
            da: z(r * d)?,
            dq: z(r * d)?,
            dk: z(r * d)?,
            dv: z(r * d)?,
            dh1a: z(r * d)?,
            dh1b: z(r * d)?,
            dh1c: z(r * d)?,
            t1: z(r * d)?,
            dh1: z(r * d)?,
            dxln: z(r * d)?,
            stats: z(2 * r)?,
            dot: z(batch * c.heads * t)?,
            ds: z(batch * c.heads * t * t)?,
            junk_v: z(v)?,
        })
    }
}
